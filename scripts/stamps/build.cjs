// node scripts/stamps/build.cjs [--images | --check]
const fs=require('fs'),path=require('path'),assert=require('assert/strict');
const root=path.resolve(__dirname,'../..'),mini=path.join(root,'miniprogram');
const source=require(path.join(root,'design/stamps/catalog.v1.json'));
const catalog={...source,items:source.items.map((item,i)=>({...item,column:i%5,row:Math.floor(i/5),previewPackage:'stamps'+Math.floor(i/25)}))};
const rewards=require(path.join(root,'cloudfunctions/atlas-checkin/stamp-rewards.json')).rewards;
assert.equal(catalog.items.length,100);assert.equal(new Set(catalog.items.map(x=>x.id)).size,100);
assert.equal(rewards.length,60);assert.equal(new Set(rewards.map(x=>x.itemId)).size,60);
rewards.forEach((r,i)=>{assert.equal(r.day,2+i*7);assert.equal(r.type,'stamp');assert.equal(r.id,'stamp:'+r.itemId);assert(catalog.items.some(x=>x.id===r.itemId&&!x.free))});
const targets=[['lib/stamp-catalog.js',catalog],['lib/stamp-rewards.js',rewards.map(({itemId,day})=>({itemId,day}))]];
function write(file,data){fs.mkdirSync(path.dirname(file),{recursive:true});if(!fs.existsSync(file)||!fs.readFileSync(file).equals(Buffer.from(data)))fs.writeFileSync(file,data)}
for(const [file,data]of targets){
 const p=path.join(mini,file);
 if(process.argv.includes('--check'))assert.deepEqual(require(p),data);
 else if(file==='lib/stamp-catalog.js'){
  const compact=data.items.map(x=>[x.name,x.motif]);
  write(p,`// Generated by scripts/stamps/build.cjs.\nconst series=${JSON.stringify(data.series)};const entries=${JSON.stringify(compact)};module.exports={version:1,series,items:entries.map(([name,motif],i)=>({id:'stamp-'+String(i+1).padStart(3,'0'),type:'stamp',name,seriesId:series[Math.floor(i/10)].id,ink:series[Math.floor(i/10)].ink,motif,frame:i%5,number:i+1,column:i%5,row:Math.floor(i/5),description:name+'，为这一程留下一枚旅途印记。',free:false,previewPackage:'stamps'+Math.floor(i/25)}))};\n`);
 }else write(p,'// Generated by scripts/stamps/build.cjs.\nmodule.exports = '+JSON.stringify(data)+';\n');
}
function checkArtwork(){
 const manifest=require(path.join(root,'design/stamps/artwork.v2.json'));
 assert.equal(manifest.items.length,100);assert.equal(new Set(manifest.items.map(x=>x.id)).size,100);
 const crypto=require('crypto'),sizes={};
 for(const item of catalog.items){
  const entry=manifest.items.find(x=>x.id===item.id);assert(entry,'Missing artwork '+item.id);
  const master=fs.readFileSync(path.resolve(root,entry.file));assert.equal(crypto.createHash('sha256').update(master).digest('hex'),entry.sha256,'Master changed: '+item.id);
  const file=path.join(mini,item.previewPackage,'assets',item.id+'.png'),bytes=fs.statSync(file).size;
  sizes[item.previewPackage]=(sizes[item.previewPackage]||0)+bytes;
 }
 for(const [name,size]of Object.entries(sizes)){
  assert(size<1850000,name+' exceeds image budget');
  const expected=catalog.items.filter(x=>x.previewPackage===name).map(x=>x.id+'.png').sort();
  assert.deepEqual(fs.readdirSync(path.join(mini,name,'assets')).sort(),expected,'Unexpected or stale artwork in '+name);
 }
 console.log('100 source hashes, packaged images and 60 rewards verified:',sizes);
}
if(process.argv.includes('--check')){checkArtwork();process.exit(0)}
if(!process.argv.includes('--images'))process.exit(0);
async function buildImages(){
 const manifestPath=path.join(root,'design/stamps/artwork.v2.json');
 assert(fs.existsSync(manifestPath),'Approved artwork manifest is required; vector fallback is prohibited');
 const manifest=JSON.parse(fs.readFileSync(manifestPath)),crypto=require('crypto');
 assert.equal(manifest.items.length,100);
 const sharp=require(process.env.ATLAS_SHARP_MODULE||'C:/Users/Fconu/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/sharp');
 const {createCanvas,loadImage}=require(process.env.ATLAS_CANVAS_MODULE||'C:/Users/Fconu/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/@napi-rs/canvas');
 const sheet=createCanvas(400,1600),sc=sheet.getContext('2d');sc.fillStyle='#f6f3e9';sc.fillRect(0,0,400,1600);
 const review=createCanvas(1600,1600),rc=review.getContext('2d');rc.fillStyle='#f6f3e9';rc.fillRect(0,0,1600,1600);
 const sizes={stamps0:0,stamps1:0,stamps2:0,stamps3:0};
 for(const [i,item]of catalog.items.entries()){
  const entry=manifest.items.find(x=>x.id===item.id);assert(entry,'Missing '+item.id);
  const master=path.resolve(root,entry.file),source=fs.readFileSync(master);
  assert.equal(crypto.createHash('sha256').update(source).digest('hex'),entry.sha256,'Master changed: '+item.id);
  const {data,info}=await sharp(source).resize(384,384,{fit:'contain',background:{r:0,g:0,b:0,alpha:0}}).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  for(let j=0;j<data.length;j+=4)if(data[j+3]<=4)data.fill(0,j,j+4);
  const b=await sharp(data,{raw:{width:info.width,height:info.height,channels:4}}).png({palette:true,colors:64,dither:0,effort:10,compressionLevel:9}).toBuffer();
  write(path.join(mini,item.previewPackage,'assets',item.id+'.png'),b);sizes[item.previewPackage]+=b.length;
  const im=await loadImage(b);sc.drawImage(im,item.column*80,item.row*80,80,80);rc.drawImage(im,(i%10)*160,Math.floor(i/10)*160,160,160);
 }
 assert(Object.values(sizes).every(n=>n<1850000),'Artwork subpackage exceeds budget: '+JSON.stringify(sizes));
 write(path.join(mini,'assets/collection/stamps.jpg'),sheet.toBuffer('image/jpeg',60));
 write(path.resolve(root,'../../outputs/reviews/2026-11-17/stamps-faithful/overview.png'),review.toBuffer('image/png'));
 console.log('Faithful bitmap artwork built:',sizes);
}
buildImages().catch(e=>{console.error(e);process.exitCode=1});
