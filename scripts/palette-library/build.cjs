// node scripts/palette-library/build.cjs [--check | --images]
// --images requires @napi-rs/canvas (or ATLAS_CANVAS_MODULE pointing to it).
const fs = require('node:fs');
const path = require('node:path');
const repo = path.resolve(__dirname, '../..');
const mini = path.join(repo, 'miniprogram');
const source = require(path.join(repo, 'design/palette-library/catalog.v1.json'));
const target = path.join(mini, 'lib/collection-catalog.js');
function writeChanged(file, content) {
  const next = Buffer.isBuffer(content) ? content : Buffer.from(content);
  if (fs.existsSync(file) && fs.readFileSync(file).equals(next)) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, next);
  return true;
}
const seen = new Set();
const catalog = {
  version: source.schemaVersion,
  series: source.series,
  items: source.entries.map((item, index) => {
    if (seen.has(item.id)) throw Error('Duplicate palette: ' + item.id);
    seen.add(item.id);
    if (!item.description || !item.previewAsset ||
        item.previewAsset.path !== `/${item.previewAsset.package}/maps/${item.id}.jpg`)
      throw Error('Incomplete palette: ' + item.id);
    return { id: item.id, type: 'palette', name: item.name,
      description: item.description, seriesId: item.seriesId, colors: item.colors,
      free: item.releaseCohort === 'starter-free', column: index % 5,
      row: Math.floor(index / 5), previewAsset: item.previewAsset };
  }),
};
if (catalog.items.length !== 100) throw Error('Launch catalog must contain 100 palettes');
if (process.argv.includes('--check')) {
  const actual = require(target);
  if (JSON.stringify(actual) !== JSON.stringify(catalog)) throw Error('Runtime catalog differs from design source');
  for (const item of catalog.items)
    if (!fs.existsSync(path.join(mini, item.previewAsset.path.slice(1))))
      throw Error('Missing preview: ' + item.id);
  console.log('Catalog and 100 preview references verified');
  process.exit(0);
}
writeChanged(target, '// Generated by scripts/palette-library/build.cjs.\nmodule.exports = ' + JSON.stringify(catalog, null, 2) + ';\n');
if (!process.argv.includes('--images')) process.exit(0);

const {createCanvas, GlobalFonts} = require(process.env.ATLAS_CANVAS_MODULE || '@napi-rs/canvas');
if (process.platform === 'win32') GlobalFonts.registerFromPath('C:/Windows/Fonts/msyh.ttc', 'sans-serif');
const {calculate} = require(path.join(mini, 'lib/flights'));
const {renderPoster, posterDimensions} = require(path.join(mini, 'lib/poster'));
const sample = calculate([['PVG','LHR'],['PVG','LAX'],['PVG','SYD'],['PVG','SIN']]
  .map(([from,to]) => ({date:'2026-10-01',from,to})), require(path.join(mini,'lib/airports')), '2026-11-15', false);
const sheet = createCanvas(1200, 2560), ctx = sheet.getContext('2d');
const sizes = new Map();
// Palette colors do not alter geometry. Reuse one prepared layout and two canvases.
const dim = posterDimensions(sample,2160,{posterContent:[]});
const height = Math.round(dim.mapHeight * 1080 / 1600 * 2);
const canvas = createCanvas(2160,dim.height), cropped = createCanvas(2160,height);
const cropContext = cropped.getContext('2d');
let changedImages = 0;
for (const [index, item] of catalog.items.entries()) {
  const options = {colors:item.colors,posterContent:[]};
  renderPoster(canvas,sample,options,dim);
  if (height !== item.previewAsset.height || canvas.width !== item.previewAsset.width)
    throw Error('Preview geometry changed; update asset revision explicitly: ' + item.id);
  cropContext.drawImage(canvas,0,230,2160,height,0,0,2160,height);
  const output = path.join(mini,item.previewAsset.path.slice(1)), buffer = cropped.toBuffer('image/jpeg',85);
  if (writeChanged(output,buffer)) changedImages++;
  sizes.set(item.previewAsset.package,(sizes.get(item.previewAsset.package)||0)+buffer.length);
  const x=index%5*240,y=Math.floor(index/5)*128,k=Math.min(240/2160,128/height);
  ctx.fillStyle=item.colors.background;ctx.fillRect(x,y,240,128);
  ctx.drawImage(cropped,x+(240-2160*k)/2,y+(128-height*k)/2,2160*k,height*k);
}
canvas.width=canvas.height=cropped.width=cropped.height=1;
if ([...sizes.values()].some(size=>size>=1900000)) throw Error('Preview subpackage exceeds budget');
const sheetChanged = writeChanged(path.join(mini,'assets/collection/palettes.jpg'),sheet.toBuffer('image/jpeg',85));
console.log('Verified generated palette images', {changedImages,sheetChanged,packages:Object.fromEntries(sizes)});
