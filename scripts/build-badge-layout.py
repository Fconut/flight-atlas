"""Precompute badge alpha bounds; reads artwork without modifying image files.
Requires Python 3 and Pillow: python -m pip install Pillow
Run from any directory: python scripts/build-badge-layout.py
"""
from pathlib import Path
import hashlib
import json
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
def layout_for(path):
    raw = path.read_bytes()
    with Image.open(path) as image:
        width, height = image.size
        alpha = image.convert("RGBA").getchannel("A")
        bounds = alpha.point(lambda value: 255 if value > 32 else 0).getbbox()
    transform = ""
    if bounds:
        left, top, right, bottom = bounds
        edge = max(width, height)
        scale = .96 * edge / max(right-left, bottom-top)
        x = (width/2-(left+right)/2)/edge*scale*100
        y = (height/2-(top+bottom)/2)/edge*scale*100
        transform = f"translate({x}%, {y}%) scale({scale})"
    return {"width":width,"height":height,"bounds":list(bounds) if bounds else None,
            "sha256":hashlib.sha256(raw).hexdigest(),"transform":transform}
def main():
    files = sorted((ROOT/"dist/assets/aircraft-ribbon").glob("*.webp"))
    if not files:
        raise SystemExit("No badge artwork found")
    layout = {path.stem:layout_for(path) for path in files}
    output = ROOT/"dist/badge-layout.js"
    output.write_text("// Generated by scripts/build-badge-layout.py; do not edit.\nconst fleetBadgeLayout=Object.freeze("+json.dumps(layout,ensure_ascii=False,separators=(",",":"))+");\n",encoding="utf-8")
    print(f"Generated layout for {len(layout)} badges")
if __name__ == "__main__":
    main()
